import importlib.util
import json
from pathlib import Path
import subprocess
import sys
import unittest

root = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location('native_window', root / 'native-window.py')
w = importlib.util.module_from_spec(spec); sys.modules[spec.name] = w; spec.loader.exec_module(w)

def record(n=1):
    return dict(dataset='cdspnative_test/fixture', object=n, generation=3, size=262144,
                mtime_sec=100000, mtime_nsec=0, offset=0, length=131072)

class TestDevice(unittest.TestCase):
    def test_splits_2049_query_inventory_and_preserves_identity(self):
        calls = []
        def run(args, input=None, capture_output=False):
            rows = input.decode().splitlines(); calls.append(len(rows))
            records = [dict(zip(w.FIELDS, map(int, line.split()))) for line in rows]
            for r in records: r.update(error=0, flags=1, block_size=131072)
            return subprocess.CompletedProcess(args, 0, json.dumps(dict(count=len(rows), records=records)).encode(), b'')
        d=w.Device('client', record()['dataset'], 1, 2, runner=run)
        out=d.query([record(i+1) for i in range(2049)])
        self.assertEqual(calls,[2048,1]); self.assertEqual(len(out),2049)

    def test_query_refuses_changed_identity(self):
        def run(args, **kwargs):
            r=record(); r.pop('dataset'); r['generation']+=1
            return subprocess.CompletedProcess(args,0,json.dumps(dict(count=1,records=[r])).encode(),b'')
        d=w.Device('client',record()['dataset'],1,2,runner=run)
        with self.assertRaisesRegex(ValueError,'changed input identity'): d.query([record()])

    def test_cross_dataset_refuses_before_external_call(self):
        def run(*args,**kwargs): self.fail('must not call client')
        d=w.Device('client','cdspnative_other',1,2,runner=run)
        with self.assertRaisesRegex(ValueError,'cross-dataset'): d.command('warm',records=[record()])

    def test_truncated_read_refused(self):
        def run(args, **kwargs): return subprocess.CompletedProcess(args,0,b'x',b'')
        d=w.Device('client',record()['dataset'],1,2,runner=run)
        with self.assertRaisesRegex(ValueError,'truncated'): d.read(record(),0,2)

    def test_object_cache_crosses_boundary_without_extra_or_outside_reads(self):
        data=bytes(range(256))*200
        class Backend:
            def __init__(self): self.calls=[]
            def read(self,identity,at,n): self.calls.append((at,n)); return data[at:at+n]
        b=Backend(); r=w.ObjectReader(b,{'size':len(data)},chunk_size=1024,cache_chunks=2)
        self.assertEqual(r.read_at(1000,80),data[1000:1080])
        self.assertEqual(b.calls,[(0,1024),(1024,1024)])
        r.read_at(1020,8); self.assertEqual(len(b.calls),2)
        with self.assertRaisesRegex(ValueError,'outside'): r.read_at(len(data)-1,2)

    def test_physical_order_and_full_block_budget_split(self):
        rs=[record(i) for i in range(1,19)]
        queried={w.planner.record_key(r):dict(vdev=0,dva_offset=19-r['object'],birth=4,block_size=16<<20) for r in rs}
        batches=w.physical_batches(rs,queried)
        self.assertEqual([len(x) for x in batches],[16,2])
        self.assertEqual([r['object'] for b in batches for r in b],list(range(18,0,-1)))


# Main-path regression fixtures: generated bytes + a fake client runner only.
# They exercise the actual Device/ObjectReader/planner/filter/result pipeline.
import contextlib
import hashlib
import io
import tempfile
from unittest import mock

class TestPrivateWindowPipeline(unittest.TestCase):
    def fixture(self, dataset):
        layout=w.planner.Layout.from_admitted_bytes((root/'planner/catalog-layout.json').read_bytes())
        table=bytearray()
        for obj in [1001,1002]:
            row=bytearray(1608)
            f=layout.fields['dataset']; name=dataset.encode()
            row[f['offset']:f['offset']+len(name)]=name
            values={'dataset_id':7,'st_dev':7,'st_ino':obj,'st_mode':0o100644,
                    'st_gen':3,'st_size':4096,'st_mtim.tv_sec':100000,
                    'st_mtim.tv_nsec':0,'block_size':4096,'method':1,'chunked':0}
            for name,value in values.items():
                f=layout.fields[name]
                row[f['offset']:f['offset']+f['size']]=value.to_bytes(f['size'],'little')
            table+=row
        native=b''.join((f'{7:020d} '+ 'a'*64 + f' {4096:020d} {i:020d} {0:020d} {4096:020d} {4096:020d}\n').encode() for i in range(2))
        return {10000:bytes(table),10001:native}

    def run_window(self, mode='ok', declared_layout_hash=None, host='cdsprefetch-native-20261024', separate_catalog=False):
        dataset='cdspnative_test/fixture'; captures=self.fixture(dataset)
        calls=[]; original_device=w.Device
        def runner(args,input=None,capture_output=False):
            op=args[1]; calls.append(op)
            expected_dataset=dataset+'/catalogs' if separate_catalog and op in ('stat','read') else dataset
            self.assertEqual(args[2],expected_dataset)
            self.assertEqual(args[3:5],['12','56' if separate_catalog and op in ('stat','read') else '34'])
            if op=='stat':
                obj=int(args[5]); data=dict(object=obj,generation=1,size=len(captures[obj]),mtime_sec=1,mtime_nsec=0)
            elif op=='read':
                obj,gen,size,sec,nsec,at,n=map(int,args[5:])
                return subprocess.CompletedProcess(args,0,captures[obj][at:at+n],b'')
            else:
                records=[dict(zip(w.FIELDS,map(int,line.split()))) for line in input.decode().splitlines()]
                for r in records:
                    r.update(error=0,flags=1 if op=='query' else 7,block_size=4096,
                             birth=4,vdev=0,dva_offset=r['object']*4096,asize=4096,
                             dva0_word0=r['object'],dva0_word1=r['object']*4096)
                if op=='query' and mode=='query_error':
                    records[-1].update(error=116,flags=0)
                if op=='warm' and mode=='truncated': records=records[:1]
                if op=='warm' and mode=='changed_identity': records[-1]['generation']+=1
                if op=='warm' and mode=='missing_flags':
                    for r in records: r['flags']=1
                if op=='warm' and mode=='empty': records=[]
                n=len(records)
                data=dict(count=n,records=records,issued_arc_requests=n if op=='warm' else 0,
                          completed_requests=n if op=='warm' else 0)
                if op=='warm' and mode=='zero_issued':
                    data.update(issued_arc_requests=0,completed_requests=0)
                if op=='warm' and mode=='nonzero_exit':
                    return subprocess.CompletedProcess(args,1,json.dumps(data).encode(),b'local client failure')
            return subprocess.CompletedProcess(args,0,json.dumps(data).encode(),b'')
        with tempfile.TemporaryDirectory() as temporary:
            base=Path(temporary); client=base/'client'; client.write_bytes(b'owned fake client')
            output=base/'result.json'; layout=root/'planner/catalog-layout.json'
            argv=['native-window.py','--client',str(client),'--client-sha256',hashlib.sha256(client.read_bytes()).hexdigest(),
                  '--dataset',dataset,'--pool-guid','12','--dataset-guid','34','--file-object','10000',
                  '--native-object','10001','--layout',str(layout),'--layout-sha256',
                  declared_layout_hash or hashlib.sha256(layout.read_bytes()).hexdigest(),
                  '--execute','--output',str(output)]
            if separate_catalog:
                argv += ['--catalog-dataset',dataset+'/catalogs','--catalog-pool-guid','12','--catalog-dataset-guid','56']
            error=None
            with mock.patch.object(sys,'argv',argv),mock.patch.object(w.os,'geteuid',return_value=0), \
                 mock.patch.object(w.socket,'gethostname',return_value=host), \
                 mock.patch.object(w.subprocess,'check_output',return_value=b'bhyve\n'), \
                 mock.patch.object(w,'Device',side_effect=lambda *a:original_device(*a,runner=runner)), \
                 contextlib.redirect_stdout(io.StringIO()):
                try: w.main()
                except (Exception,SystemExit) as exception: error=exception
            result=json.loads(output.read_text()) if output.exists() else None
            return result,error,calls

    def test_private_window_happy_path_executes_through_actual_loader(self):
        result,error,calls=self.run_window()
        self.assertIsNone(error)
        self.assertEqual(result['status'],'PRIVATE_WINDOW_PREFETCH_REQUESTS_DRAINED')
        self.assertEqual(calls.count('warm'),1)
        self.assertEqual(result['filter']['request_count'],2)

    def test_warm_must_cover_submitted_batch_and_identity(self):
        for mode in ['empty','truncated','changed_identity','missing_flags','zero_issued','nonzero_exit']:
            with self.subTest(mode=mode):
                result,error,calls=self.run_window(mode)
                self.assertEqual(calls.count('warm'),1, f'failure must occur at warm validation, not earlier: {error}')
                self.assertTrue(error is not None or result['status']=='PRIVATE_WINDOW_PARTIAL_OR_ERROR',
                                f'{mode} produced a false drained receipt: {result}')

    def test_query_error_is_partial_and_does_not_warm_failed_pair(self):
        result,error,calls=self.run_window('query_error')
        self.assertIsNone(error)
        self.assertEqual(result['status'],'PRIVATE_WINDOW_PARTIAL_OR_ERROR')
        self.assertTrue(result['filter']['coverage_errors'])
        self.assertEqual(calls.count('warm'),0)

    def test_catalogs_and_target_use_independent_dataset_bindings(self):
        result,error,calls=self.run_window(separate_catalog=True)
        self.assertIsNone(error)
        self.assertEqual(result['status'],'PRIVATE_WINDOW_PREFETCH_REQUESTS_DRAINED')
        self.assertEqual(result['catalog_binding']['dataset_guid'],56)
        self.assertEqual(result['calls']['read'],0)
        self.assertGreater(result['catalog_calls']['read'],0)

    def test_production_host_refuses_before_any_object_or_warm_call(self):
        result,error,calls=self.run_window(host='bsdsan')
        self.assertIsNotNone(error)
        self.assertRegex(str(error),'production is not admitted')
        self.assertEqual(calls,[])
        self.assertIsNone(result)

    def test_declared_layout_hash_mismatch_refuses_before_object_calls(self):
        result,error,calls=self.run_window(declared_layout_hash='0'*64)
        self.assertIsNotNone(error)
        self.assertRegex(str(error).lower(),'layout|hash')
        self.assertEqual(calls,[])
        self.assertIsNone(result)

if __name__=='__main__': unittest.main(verbosity=2)
